export function translateMedicalTerm(term: string, langCode = 'en'): string {
  if (!term) return '';
  const cleanKey = term.toLowerCase().trim();
  if (cleanKey === 'unspecified' || cleanKey === 'not_food_related' || cleanKey === 'anytime') {
    return '';
  }

  const formDef = getMedicineFormDef(term);
  if (formDef) {
    const validLang = (['en', 'hi', 'ur', 'te', 'bn', 'mr', 'ta'].includes(langCode)
      ? langCode
      : 'en') as 'en' | 'hi' | 'ur' | 'te' | 'bn' | 'mr' | 'ta';
    return formDef.label[validLang] || formDef.label.en;
  }

  const entry = MEDICAL_GLOSSARY[cleanKey];
  if (entry) {
    return entry[langCode] || entry['en'] || term;
  }
  return term;
}

